class SanoidRule(TypedDict):
    """A single sanoid policy rule for one dataset.

    Returned by ``_classify``, which returns ``None`` instead when the
    dataset is to be skipped (e.g. children covered by a parent's
    recursive rule).

    Every key is required. This used to be a ``total=False`` TypedDict so
    that ``_classify``'s skip case could ``return {}``, but that made the
    type lie about the populated case: every consumer here
    (``_format_rule``, ``_print_rules_review``, ``_rule_to_settings``)
    indexes all three keys unconditionally, and only ever receives fully
    populated rules. Separating "no rule" into ``None`` lets the type
    checker verify that each populated return really does set all three.

      template:   "production" | "minimal" | "drained" | None  (None ⇒ autosnap=no)
      recursive:  whether the rule applies to descendants
      explain:    short human-readable reason shown in the review table
    """

    template: str | None
    recursive: bool
    explain: str


# One sanoid.conf section's settings: {"use_template": "minimal", ...}.
SectionSettings = dict[str, str]


class SanoidDiff(TypedDict):
    """What ``_diff_rules`` found between the current sanoid.conf and the
    rules zark would generate now.

    The five lists do not share an element type, which is why this is a
    TypedDict and not a ``dict[str, list]``: added/removed/manual carry
    (name, settings), while changed/templates carry
    (name, before, after).

      added:     sections that will appear
      removed:   sections that will disappear
      changed:   sections whose settings differ
      manual:    sections in the current file that are neither
                 managed-prefix nor templates (e.g. a user-added
                 [tank/games]). zark does not touch them, but warns.
      templates: template sections whose values disagree with the current
                 generator. Kept apart from `changed` because the value
                 space is different (daily/weekly/monthly counts vs.
                 use_template/recursive). Empty when they already match.
    """

    added: list[tuple[str, SectionSettings]]
    removed: list[tuple[str, SectionSettings]]
    changed: list[tuple[str, SectionSettings, SectionSettings]]
    manual: list[tuple[str, SectionSettings]]
    templates: list[tuple[str, SectionSettings, SectionSettings]]


def _detect_ubuntu_ds() -> str:
    r = sh.run(
        "zfs list -H -o name -r rpool/ROOT "
        + "| grep -v '^rpool/ROOT$' | grep -v '@' | awk -F/ 'NF==3' | head -1",
    )
    return r.output.replace("rpool/ROOT/", "") if r.ok and r.output else ""


# ── Dataset → policy classification ──────────────────────────────────────────


def _classify(  # pylint: disable=too-many-return-statements
    ds: DatasetInfo,
    ubuntu_name: str,
) -> SanoidRule | None:
    """
    Return the sanoid rule for a single dataset, or None to skip it.

    See ``SanoidRule`` for the shape of a returned rule.
    """
    name = ds.name

    # zvols: never autosnap (see module docstring)
    if ds.type == "volume":
        return {
            "template": None,
            "recursive": False,
            "explain": "zvol - backed up via prepare/recover",
        }

    # Pool roots: minimal, not recursive (children own their subtrees)
    if "/" not in name:
        return {"template": "minimal", "recursive": False, "explain": "pool root"}

    # Known critical paths
    if name == f"rpool/ROOT/{ubuntu_name}":
        return {"template": "production", "recursive": True, "explain": "live system"}
    if name == "rpool/USERDATA":
        return {"template": "production", "recursive": True, "explain": "user data"}
    if name == "rpool/ROOT":
        return {"template": "minimal", "recursive": False, "explain": "boot environments container"}

    # Children of rpool/ROOT (the boot environment itself, not the named ubuntu_*)
    # are already covered by the recursive rule on rpool/ROOT/<ubuntu>; skip.
    if name.startswith("rpool/ROOT/") and name != f"rpool/ROOT/{ubuntu_name}":
        return None

    # Children covered recursively by their parent's rule - skip to avoid
    # overlapping rules that confuse sanoid (see issue 627 upstream).
    covered_prefixes = (
        f"rpool/ROOT/{ubuntu_name}/",
        "rpool/USERDATA/",
        "bpool/BOOT/",
    )
    if name.startswith(covered_prefixes):
        return None

    # bpool/BOOT holds kernels, initramfs, grub config - content the user
    # may legitimately want to roll back months in time after a bad
    # apt upgrade. production retention (up to ~3 months) aligns this with the
    # rest of the system; the extra hourly snapshots cost nothing because
    # /boot doesn't change between hours, so ZFS deduplicates the blocks.
    if name == "bpool/BOOT":
        return {"template": "production", "recursive": True, "explain": "boot chain"}

    # Top-level under any pool that we haven't classified above:
    # rpool/var, rpool/libvirt, anything new the user added.
    # Defensive default: minimal+recursive covers everything in the subtree.
    parts = name.split("/")
    if len(parts) == 2:
        return {"template": "minimal", "recursive": True, "explain": "discovered (defensive)"}

    # Anything deeper that wasn't matched above and wasn't covered by a
    # recursive parent rule - also minimal+recursive (covers e.g. children
    # of rpool/var if rpool/var itself wasn't a dataset).
    return {"template": "minimal", "recursive": True, "explain": "discovered nested"}


# A subtree excluded from snapshots (D8, M5b-6 6a): sanoid takes none, and
# with autoprune and every count at 0 removes the old ones at its next prune
# (sanoid v2.3.0 sanoid:325-366).
DRAINED = "drained"
_DRAINED_SETTINGS = {
    "autosnap": "no",
    "autoprune": "yes",
    "frequently": "0",
    "hourly": "0",
    "daily": "0",
    "weekly": "0",
    "monthly": "0",
    "yearly": "0",
    "recursive": "yes",
}


def _format_rule(name: str, rule: SanoidRule) -> list[str]:
    """Render one sanoid.conf section for the given (name, rule)."""
    lines = [f"[{name}]"]
    if rule["template"] == DRAINED:
        lines += [f"{k} = {v}" for k, v in _DRAINED_SETTINGS.items()]
    elif rule["template"] is None:
        lines.append("autosnap = no")
        lines.append("autoprune = no")
    else:
        lines.append(f"use_template = {rule['template']}")
        lines.append(f"recursive = {'yes' if rule['recursive'] else 'no'}")
    return lines


def _discover_rules(
    zfs: ZFSQuery, ubuntu_name: str, drained: frozenset[str] = frozenset()
) -> list[tuple[str, SanoidRule]]:
    """
    Return a list of (dataset_name, rule) for every dataset that should appear
    in sanoid.conf, in the order they should be written.

    Two-pass approach:
      1. Classify each dataset independently.
      2. Drop rules whose parent has ``recursive=yes`` AND would apply the
         same effective policy. Two overlapping rules with the same policy
         add noise; two with *different* policies (e.g. zvol exclusion under
         a recursive filesystem parent) must both stay so the more specific
         one overrides the inherited one.
      3. The subtrees in ``drained`` (excluded from snapshots) are written
         outside every recursive rule (:func:`_split_around`).
    """
    initial: list[tuple[str, SanoidRule]] = []
    seen: set[str] = set()

    for pool in ("rpool", "bpool"):
        if not zfs.pool_exists(pool):
            continue
        for ds in zfs.list_datasets(pool, recursive=True):
            if ds.name in seen:
                continue
            seen.add(ds.name)
            rule = _classify(ds, ubuntu_name)
            if rule is not None:
                initial.append((ds.name, rule))

    rules_by_name = dict(initial)

    def _nearest_recursive_ancestor(name: str) -> SanoidRule | None:
        parts = name.split("/")
        for i in range(1, len(parts)):
            ancestor = "/".join(parts[:-i])
            anc_rule = rules_by_name.get(ancestor)
            if anc_rule is not None and anc_rule["recursive"]:
                return anc_rule
        return None

    pruned: list[tuple[str, SanoidRule]] = []
    for name, rule in initial:
        anc = _nearest_recursive_ancestor(name)
        if anc is None:
            pruned.append((name, rule))
            continue
        # The ancestor's recursive rule already covers this dataset.
        # Drop our entry only if its policy is the same; otherwise keep
        # it as an explicit override (e.g. zvol under recursive filesystem).
        if anc["template"] == rule["template"] and anc["recursive"] == rule["recursive"]:
            continue  # redundant - drop
        pruned.append((name, rule))

    return _split_around(pruned, sorted(seen), drained) if drained else pruned


def _split_around(
    rules: list[tuple[str, SanoidRule]], datasets: list[str], drained: frozenset[str]
) -> list[tuple[str, SanoidRule]]:
    """``rules`` with every subtree in ``drained`` as a drained section of its
    own, and no recursive rule containing one (M5b-6 6a).

    sanoid reads its sections in Perl hash order, and a recursive section
    writes its values into every child's config, autosnap included, before
    or after the child's own section was read (sanoid v2.3.0 sanoid:970,
    :1075-1115): a child section inside a recursive rule is honoured on some
    runs only. So a recursive rule above a drained subtree becomes a
    non-recursive section for each dataset on the way down to it, and a
    recursive one for each other subtree that branches off that way. The
    rules inside a drained subtree go: the drained section covers it.
    """
    by_name = dict(rules)

    def inside(name: str) -> str:
        return exclusions.covering(name, set(drained))

    def children(name: str) -> list[str]:
        return [d for d in datasets if d.rsplit("/", 1)[0] == name and "/" in d]

    def expand(name: str, rule: SanoidRule) -> list[tuple[str, SanoidRule]]:
        if name in drained:
            return [(name, {"template": DRAINED, "recursive": True, "explain": "excluded"})]
        if not any(exclusions.under(t, name) for t in drained):
            return [(name, rule)]
        out: list[tuple[str, SanoidRule]] = [(name, {**rule, "recursive": False})]
        for child in children(name):
            if child in by_name and child not in drained:
                continue  # it has a rule of its own, expanded in its turn
            out += expand(child, rule)
        return out

    out: list[tuple[str, SanoidRule]] = []
    for name, rule in rules:
        if inside(name) and name not in drained:
            continue
        out += expand(name, rule) if rule["recursive"] or name in drained else [(name, rule)]
    for top in sorted(drained):
        if top not in dict(out):
            out.append((top, {"template": DRAINED, "recursive": True, "explain": "excluded"}))
    return out


def _drained() -> frozenset[str]:
    """The subtrees excluded from snapshots, as origin declares them, read
    strictly (raises :class:`survey.ReadError`): a failed read is not
    "nothing excluded", which would put them back in the recursive rules
    (M5bR-4)."""
    pools = survey.source_pools()
    origin = survey.read_origin(pools, strict=True)
    return exclusions.read(pools, origin, strict=True).no_snapshot


def _generate_sanoid_conf(
    rules: list[tuple[str, SanoidRule]],
    preserve_manual: list[tuple[str, dict[str, str]]] | None = None,
) -> str:
    """Build the full sanoid.conf text from a list of (name, rule) tuples.

    If ``preserve_manual`` is given (list of ``(section_name, settings_dict)``
    pairs), those sections are emitted verbatim between the managed rules and
    the templates. This is how user-added sections like ``[tank/games]``
    survive a sanoid.conf regeneration: zark rewrites its own rules but never
    discards what it doesn't manage.
    """
    out: list[str] = [
        "# Generated by zark setup. Edit freely; zark will ask before overwriting.",
        "# Sections under rpool/* and bpool/* are managed by zark; others are",
        "# preserved untouched across regenerations.",
        "",
    ]
    for name, rule in rules:
        out.extend(_format_rule(name, rule))
        out.append("")

    if preserve_manual:
        out.append("# ── Preserved user sections (not managed by zark) ──")
        out.append("")
        for name, settings in preserve_manual:
            out.append(f"[{name}]")
            for key, value in settings.items():
                out.append(f"{key} = {value}")
            out.append("")

    # Templates - ``template_minimal`` (``daily=14 weekly=8 monthly=3``)
    # is used by the container datasets (``rpool``, ``rpool/ROOT``,
    # ``rpool/var``, ``bpool``). Drives are anchored on bookmarks and do
    # not depend on these values; a drive anchored only on shared
    # snapshots (written by zark 1.x, before its first zark 2 backup) stays
    # incremental for 62 days after its last backup with either template
    # (lib/sanoid_retention.py). Cost: ~25 snapshots per container dataset
    # and a few KB of metadata each, since container datasets carry only
    # metadata. ``template_production`` is unchanged from upstream examples.
    out.extend(
        [
            "[template_production]",
            "frequently = 0",
            "hourly = 24",
            "daily = 7",
            "weekly = 4",
            "monthly = 3",
            "yearly = 0",
            "autoprune = yes",
            "autosnap = yes",
            "",
            "[template_minimal]",
            "frequently = 0",
            "hourly = 0",
            "daily = 14",
            "weekly = 8",
            "monthly = 3",
            "yearly = 0",
            "autoprune = yes",
            "autosnap = yes",
        ],
    )
    return "\n".join(out) + "\n"


def _print_rules_review(log: Log, rules: list[tuple[str, SanoidRule]]) -> None:
    """Show the discovered datasets and the rule each will get, for review."""
    log.info("Sanoid policy plan:")
    log.info("")
    width = max(len(n) for n, _ in rules) if rules else 30
    for name, rule in rules:
        if rule["template"] == DRAINED:
            policy = "no snapshots (drained)"
        elif rule["template"] is None:
            policy = "autosnap=no"
        else:
            policy = rule["template"]
            if rule["recursive"]:
                policy += " (recursive)"
        # Indented two spaces so it sits visually under [INFO]
        log.info(f"  {name:<{width}}  →  {policy:<22}  ({rule['explain']})")
    log.info("")


# ── sanoid.conf comparison ────────────────────────────────────────────────────
#
# When `setup` runs against an existing sanoid.conf, we want to tell the user
# exactly what will change instead of asking them to compare two long blocks
# in their head. The flow is:
#
#   1. Parse the current sanoid.conf into a {section_name: {key: value}} dict.
#   2. Build the planned sections from the discovered rules in the same shape.
#   3. Diff the two: what's new (+), gone (-), modified (~), and what manual
#      sections the user has that zark doesn't manage.
#
# Templates ([template_*]) are intentionally not diffed - the generator emits
# fixed templates that don't depend on user state.


_MANAGED_PREFIXES = ("rpool", "bpool")

# Expected key/value pairs for ``[template_minimal]``.
# When ``zark setup`` parses an existing ``sanoid.conf`` and finds the
# template differs from this, the diff includes a ``template_minimal``
# entry so the user is shown the migration before being asked to
# apply it. The values must match what ``_generate_sanoid_conf``
# emits (hardcoded above) - keeping them in two places is intentional:
# the generator is the source of truth on disk, this constant is the
# source of truth for the comparison.
_TEMPLATE_MINIMAL_EXPECTED: dict[str, str] = {
    "frequently": "0",
    "hourly": "0",
    "daily": "14",
    "weekly": "8",
    "monthly": "3",
    "yearly": "0",
    "autoprune": "yes",
    "autosnap": "yes",
}


def _parse_sanoid_conf(text: str) -> dict[str, dict[str, str]]:
    """Return {section_name: {key: value}} from sanoid.conf text.

    Only sections that *could* be zark-managed (rpool/* and bpool/*) and the
    templates are returned. Comments and blank lines are skipped. Whitespace
    around keys/values is stripped.
    """
    sections: dict[str, dict[str, str]] = {}
    current: str | None = None
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("[") and line.endswith("]"):
            current = line[1:-1].strip()
            sections.setdefault(current, {})
            continue
        if current is None:
            continue
        if "=" not in line:
            continue
        key, _, value = line.partition("=")
        sections[current][key.strip()] = value.strip()
    return sections


def _rule_to_settings(rule: SanoidRule) -> dict[str, str]:
    """Convert a classified rule into the same {key: value} shape the parser
    produces, so both sides can be compared symmetrically."""
    if rule["template"] == DRAINED:
        return dict(_DRAINED_SETTINGS)
    if rule["template"] is None:
        return {"autosnap": "no", "autoprune": "no"}
    return {
        "use_template": rule["template"],
        "recursive": "yes" if rule["recursive"] else "no",
    }


def _is_managed_section(name: str) -> bool:
    """A section is zark-managed if its name starts with rpool or bpool.
    Templates (template_*) are excluded from the diff entirely."""
    if name.startswith("template_"):
        return False
    head = name.split("/", 1)[0]
    return head in _MANAGED_PREFIXES


def _diff_rules(
    current: dict[str, SectionSettings],
    planned: list[tuple[str, SanoidRule]],
) -> SanoidDiff:
    """Compare current sanoid.conf sections against the planned rules.

    See ``SanoidDiff`` for what each of the five lists holds.
    """
    planned_map: dict[str, SectionSettings] = {
        name: _rule_to_settings(rule) for name, rule in planned
    }

    added: list[tuple[str, SectionSettings]] = []
    removed: list[tuple[str, SectionSettings]] = []
    changed: list[tuple[str, SectionSettings, SectionSettings]] = []
    manual: list[tuple[str, SectionSettings]] = []
    templates: list[tuple[str, SectionSettings, SectionSettings]] = []

    # Inspect current sections
    for name, settings in current.items():
        if not _is_managed_section(name):
            if not name.startswith("template_"):
                manual.append((name, settings))
            continue
        if name not in planned_map:
            removed.append((name, settings))
        elif planned_map[name] != settings:
            changed.append((name, settings, planned_map[name]))

    # Anything in planned that wasn't in current is a new section
    for name, settings in planned_map.items():
        if name not in current:
            added.append((name, settings))

    # Template comparison - only ``template_minimal`` is checked because
    # ``template_production`` has been stable across releases and zark
    # has never had a reason to update it. If the user's file lacks
    # ``[template_minimal]`` entirely (older custom config), we still
    # surface it as a divergence: regenerating will add it.
    current_tm = current.get("template_minimal", {})
    if current_tm != _TEMPLATE_MINIMAL_EXPECTED:
        templates.append(
            ("template_minimal", current_tm, dict(_TEMPLATE_MINIMAL_EXPECTED)),
        )

    return {
        "added": added,
        "removed": removed,
        "changed": changed,
        "manual": manual,
        "templates": templates,
    }


def _format_settings(settings: dict[str, str]) -> str:
    """Render a section's settings as a compact one-line string for diff output."""
    if "autosnap" in settings and settings["autosnap"] == "no":
        return "autosnap=no"
    parts = []
    if "use_template" in settings:
        parts.append(settings["use_template"])
    if settings.get("recursive") == "yes":
        parts.append("(recursive)")
    return " ".join(parts) if parts else "(empty)"


def _print_diff(log: Log, diff: SanoidDiff) -> None:  # pylint: disable=too-many-locals
    """Print a human-readable summary of the diff."""
    added = diff["added"]
    removed = diff["removed"]
    changed = diff["changed"]
    manual = diff["manual"]
    templates = diff["templates"]

    # Compute width across all section names for clean alignment
    all_names: list[str] = (
        [n for n, _ in added]
        + [n for n, _ in removed]
        + [n for n, _, _ in changed]
        + [n for n, _ in manual]
        + [n for n, _, _ in templates]
    )
    width = max(len(n) for n in all_names) if all_names else 30

    log.info("Changes vs current sanoid.conf:")
    for name, settings in added:
        log.info(f"  + {name:<{width}}  {_format_settings(settings)}  (NEW)")
    for name, settings in removed:
        log.info(
            f"  - {name:<{width}}  {_format_settings(settings)}  " + "(no longer in system)",
        )
    for name, before, after in changed:
        log.info(
            f"  ~ {name:<{width}}  {_format_settings(before)}  →  " + f"{_format_settings(after)}",
        )

    # Template retention diff. Distinct from regular rule changes because
    # the value space is different (daily/weekly/monthly counts vs.
    # use_template/recursive). Rendered as a per-key listing so the user
    # sees exactly which retention numbers move.
    for name, before, after in templates:
        log.info(f"  ~ [{name}] retention values:")
        all_keys = sorted(set(before) | set(after))
        for key in all_keys:
            cur_val = before.get(key, "(missing)")
            new_val = after.get(key, "(removed)")
            if cur_val == new_val:
                continue
            log.info(f"      {key:<12}  {cur_val:<10}  →  {new_val}")

    log.info("")
    if manual:
        log.info(
            f"sanoid.conf has {len(manual)} manual section(s) "
            + "zark doesn't manage - these will be PRESERVED:",
        )
        for name, settings in manual:
            log.info(f"    [{name}]  {_format_settings(settings)}")
        log.info("")


def _signed_alternative_status(name: str) -> tuple[Path | None, Path | None]:
    """Return ``(current_target, latest_path)`` for a signed alternative.

    - ``current_target``: where ``/etc/alternatives/<name>`` points to right
      now, or None if the alternative isn't installed.
    - ``latest_path``: the path of the ``.latest`` variant if present in
      the system, or None if this Ubuntu release doesn't ship the split.

    Both are returned as absolute paths. Used by the Secure Boot
    pre-check that detects systems pinned to ``.previous``.
    """
    alt_link = Path(f"/etc/alternatives/{name}")
    current = alt_link.resolve() if alt_link.exists() else None

    # The .latest variant lives next to the .signed file in the package.
    # We discover its location by reading update-alternatives metadata.
    r = sh.run(f"update-alternatives --query {name}")
    latest: Path | None = None
    if r.ok:
        for line in r.lines:
            if line.startswith("Alternative:"):
                candidate = Path(line.split(":", 1)[1].strip())
                if candidate.name.endswith(".signed.latest") and candidate.exists():
                    latest = candidate
                    break
    return current, latest


def ensure_bookmark_v2(log: Log) -> bool:
    """Make sure rpool can hold zark's bookmark anchors (M2 decision 4a).

    A raw incremental from a bookmark needs the snapshot's IV-set GUID,
    which a bookmark stores only when ``feature@bookmark_v2`` is enabled on
    the pool at bookmark creation. Enabling it cannot be undone; GRUB never
    reads rpool, so the boot chain is unaffected (bpool never gets
    bookmarks). Returns True when the feature is enabled or active.
    """
    state = bookmark_feature("rpool")
    if state in ("enabled", "active"):
        log.ok(f"rpool feature@bookmark_v2: {state}")
        return True
    if state != "disabled":
        log.warn(f"Cannot read feature@bookmark_v2 on rpool ({state or 'no value'})")
        return False
    log.warn("rpool feature@bookmark_v2 is disabled - zark backups need it for their anchors")
    log.info("  Enabling it cannot be undone. GRUB does not read rpool, so booting is unaffected.")
    if not log.ask("Enable feature@bookmark_v2 on rpool now?", default=False):
        log.warn("Not enabled - zark backup and prepare will refuse until it is")
        return False
    r = sh.run("zpool set feature@bookmark_v2=enabled rpool", log=log)
    if not r.ok:
        # e.g. rpool's 'compatibility' property does not list the feature
        log.error(f"Could not enable it: {r.stderr.strip()}")
        return False
    log.ok("rpool feature@bookmark_v2: enabled")
    return True


def _check_secure_boot_alternatives(log: Log) -> None:
    """Detect systems whose Secure Boot binaries are pinned to ``.previous``.

    Subiquity in Ubuntu 26.04 has been observed to leave the system pointing
    at the older shim (15.4-0ubuntu9, ``.signed.previous``). Recent SBAT
    revocations from fwupd then reject that binary at boot, leaving the
    system unable to start with the dreaded "Verifying shim SBAT data
    failed: Security Policy Violation". shim-signed's postinst (1.58, noble)
    also gives ``.previous`` the priority itself, with Secure Boot on, when
    the new shim's SBAT revokes an installed kernel (postinst:63-75): the
    text names both causes (M6-16 16a).

    This function inspects the alternatives for ``shimx64.efi.signed`` and
    ``grubx64.efi.signed``. If any points to ``.previous`` and a ``.latest``
    is available, it offers (with confirmation) to switch to ``.latest``,
    re-run the corresponding postinst, and update grub. Default is to NOT
    apply: touching the boot chain warrants explicit user consent.

    No-op on releases that don't ship the ``.latest``/``.previous`` split.
    """
    targets = (
        ("shimx64.efi.signed", "shim-signed"),
        ("grubx64.efi.signed", "grub-efi-amd64-signed"),
    )

    needs_fix: list[tuple[str, str, Path, Path]] = []
    for alt_name, pkg in targets:
        current, latest = _signed_alternative_status(alt_name)
        if current is None or latest is None:
            log.dbg(f"  {alt_name}: not installed or no .latest variant - skipping")
            continue
        if current == latest:
            log.ok(f"  {alt_name} → {current.name} (latest, OK)")
            continue
        # Pointed somewhere other than .latest - flag it.
        log.warn(f"  {alt_name} → {current.name} (NOT latest)")
        needs_fix.append((alt_name, pkg, current, latest))

    if not needs_fix:
        return

    log.info("")
    log.warn(
        "One or more Secure Boot binaries are NOT pinned to the latest variant.",
    )
    # Two causes (M6-16 16a): shim-signed's postinst picks .previous itself
    # under Secure Boot when the new shim revokes an installed kernel (1.58).
    log.info(
        "Either the installer left it there (the 'subiquity bug', which leaves "
        "systems unbootable after SBAT updates from fwupd), or shim's own update "
        "chose .previous because Secure Boot is on and the new shim's SBAT revokes "
        "an installed kernel: then switching can leave that kernel unbootable. "
        "Affected boot chain: ",
    )
    for alt_name, _, current, latest in needs_fix:
        log.info(f"  {alt_name}: {current.name} → would become {latest.name}")
    log.info("")
    log.info(
        "Switching is reversible (update-alternatives --set), but it does "
        "modify the boot chain. zark will not change it without your "
        "explicit consent.",
    )

    if not log.ask(
        "Switch to .latest and reinstall to ESP now? "
        "(default NO; choose Y if your firmware is up to date)",
        default=False,
    ):
        log.warn(f"Boot chain left as-is. Re-run '{zark_command()} setup' anytime to revisit.")
        return

    for alt_name, pkg, _, latest in needs_fix:
        log.info(f"Switching {alt_name} to {latest.name}...")
        r = sh.run(f"update-alternatives --set {alt_name} {latest}", log=log)
        if not r.ok:
            log.warn(f"  update-alternatives --set failed for {alt_name}")
            continue
        r = sh.run(f"dpkg-reconfigure -f noninteractive {pkg}", log=log)
        if not r.ok:
            log.warn(f"  dpkg-reconfigure {pkg} failed")
            continue
        log.ok(f"  {pkg} reconfigured ✓")

    log.info("Regenerating grub.cfg...")
    r = sh.run("update-grub", log=log)
    if r.ok:
        log.ok("update-grub succeeded ✓")
    else:
        log.warn("update-grub had warnings - review the log")


def sanoid_conf_gap(zfs: ZFSQuery) -> str:
    """ "" when /etc/sanoid/sanoid.conf holds setup's policy for this system
    (no rule added, removed or changed, template_minimal as setup writes
    it), else what setup would change (finish's setup line, M4c-10)."""
    conf = Path("/etc/sanoid/sanoid.conf")
    if not conf.exists():
        return "write /etc/sanoid/sanoid.conf"
    ubuntu_name = _detect_ubuntu_ds()
    if not ubuntu_name:
        return "configure sanoid (no rpool/ROOT/ubuntu_* boot environment found)"
    try:
        current = _parse_sanoid_conf(conf.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError):
        return "rewrite /etc/sanoid/sanoid.conf (unreadable)"
    try:
        drained = _drained()
    except survey.ReadError:
        return "could not read the exclusions"
    diff = _diff_rules(current, _discover_rules(zfs, ubuntu_name, drained))
    n = len(diff["added"]) + len(diff["removed"]) + len(diff["changed"]) + len(diff["templates"])
    return f"update /etc/sanoid/sanoid.conf ({n} section(s) differ)" if n else ""


def _install_guards(log: Log) -> None:
    """Install both backup guards on the running system, current versions.

    The APT guard stops a kernel/GRUB/ZFS package operation (unattended
    upgrades included) while a backup drive is attached or imported; the grub
    guard stops update-grub in the same situation. Overwriting brings a guard
    written by an older zark up to date (finish keeps an existing one).
    """
    apt_guard.install(target_root="", log=log)
    _ = grub_guard.install(target_root="", log=log)


def remove_installed(log: Log, root: str = "") -> int:
    """`zark setup --remove`: remove what setup installed besides sanoid's
    configuration (the alerts, the APT guard, the grub guard), as the
    package's prerm does on removal (M3P.2). A file that is not zark's is
    left and named. Returns 1 when something was left, else 0."""
    log.banner("REMOVE ZARK'S GUARDS AND ALERTS", "What setup installed besides sanoid")
    alerts.remove(log, root or "/")
    left = apt_guard.remove(root, log) + grub_guard.remove(root, log)
    lines = [f"Left, not zark's: {path}" for path in left]
    lines.append("sanoid's configuration and timer stay: they are your snapshot policy.")
    if left:
        log.banner_error("GUARDS AND ALERTS PARTLY REMOVED", lines)
        return 1
    log.banner_ok("GUARDS AND ALERTS REMOVED", lines)
    return 0


def _autosnaps(zfs: ZFS) -> dict[str, int]:
    """sanoid's snapshots on rpool and bpool (both are in sanoid.conf), by
    the snapshot's own name, not a substring of the dataset's (P0-1)."""
    return {
        pool: sum(
            1 for s in zfs.list_snapshots(pool) if s.partition("@")[2].startswith("autosnap_")
        )
        for pool in ("rpool", "bpool")
        if zfs.pool_exists(pool)
    }


def _per_pool(counts: dict[str, int]) -> str:
    return ", ".join(f"{pool} {n}" for pool, n in counts.items())


def _initial_snapshots(zfs: ZFS, log: Log) -> None:
    """Step 4: offer sanoid's first snapshots when there are none."""
    counts = _autosnaps(zfs)
    if sum(counts.values()):
        log.ok(f"{sum(counts.values())} sanoid snapshots exist ({_per_pool(counts)})")
        return
    if not log.ask("No sanoid snapshots found. Take the first ones now?", default=True):
        return
    if sh.run("sanoid --take-snapshots", log=log).ok:
        counts = _autosnaps(zfs)
        log.ok(f"Created {sum(counts.values())} snapshots ({_per_pool(counts)})")
    else:
        log.warn("sanoid --take-snapshots had errors")


def configure_sanoid(zfs: ZFSQuery, log: Log) -> bool:  # pylint: disable=too-many-branches
    """Show setup's sanoid policy for this system and write it to
    /etc/sanoid/sanoid.conf after a question (setup's step 2; ``zark
    exclude`` after a change of its snapshot flag). False when there was no
    file and the user chose not to write one."""
    ubuntu_name = _detect_ubuntu_ds()
    if not ubuntu_name:
        # Nothing typed could be right: rpool/ROOT has no child (M1P.21).
        log.fatal(
            "No boot environment under rpool/ROOT",
            causes=["rpool is not imported, or it is not Ubuntu's ZFS layout"],
            solutions=["Check: zfs list -r -d 1 rpool/ROOT"],
        )

    try:
        drained = _drained()
    except survey.ReadError as e:
        log.fatal(f"Cannot read what is excluded from snapshots: {e}")

    # Discover and classify
    rules = _discover_rules(zfs, ubuntu_name, drained)
    if not rules:
        log.fatal(
            "No datasets discovered in rpool/bpool - nothing to configure",
            solutions=["Check that rpool is imported and has datasets"],
        )
    _print_rules_review(log, rules)

    conf_path = "/etc/sanoid/sanoid.conf"
    _ = sh.run("mkdir -p /etc/sanoid")

    conf_content = _generate_sanoid_conf(rules)

    if Path(conf_path).exists():
        current_text = Path(conf_path).read_text(encoding="utf-8")
        current = _parse_sanoid_conf(current_text)
        diff = _diff_rules(current, rules)

        nothing_changes = not (
            diff["added"] or diff["removed"] or diff["changed"] or diff["templates"]
        )
        if nothing_changes:
            if diff["manual"]:
                log.ok("sanoid.conf already matches the policy above")
                log.info(
                    f"  plus {len(diff['manual'])} manual section(s) "
                    + "zark doesn't manage (preserved):",
                )
                for name, settings in diff["manual"]:
                    log.info(f"    [{name}]  {_format_settings(settings)}")
            else:
                log.ok("sanoid.conf already matches the policy above (no changes)")
        else:
            log.info(f"sanoid.conf exists at {conf_path}")
            _print_diff(log, diff)
            if log.ask("Apply these changes?"):
                _ = sh.run(
                    f"cp {conf_path} {conf_path}.backup.$(date +%Y%m%d_%H%M%S)",
                )
                # Regenerate the file, preserving any manual sections the user
                # has added that zark doesn't manage (e.g. [tank/games]).
                conf_content = _generate_sanoid_conf(
                    rules,
                    preserve_manual=diff["manual"],
                )
                _ = Path(conf_path).write_text(conf_content, encoding="utf-8")
                msg = f"sanoid.conf updated ({len(rules)} dataset rules"
                if diff["manual"]:
                    msg += f", {len(diff['manual'])} manual section(s) preserved"
                msg += ")"
                log.ok(msg)
            else:
                log.warn("sanoid.conf NOT changed - keeping the existing file")
    else:
        if log.ask("Write the policy above to /etc/sanoid/sanoid.conf?", default=True):
            _ = Path(conf_path).write_text(conf_content, encoding="utf-8")
            log.ok(f"Created {conf_path} ({len(rules)} dataset rules)")
        else:
            log.warn("sanoid.conf NOT written - you can re-run setup later")
            return False
    return True


def run(
    args: list[str],
):  # pylint: disable=too-many-statements,too-many-branches,too-many-locals
    """Run the setup process to install dependencies and configure sanoid;
    ``--remove`` removes the guards and alerts instead."""
    log = Log()
    if args == ["--remove"]:
        raise SystemExit(remove_installed(log))
    if "--remove" in args:
        # Not the full setup after being asked to remove things (M4dR-4).
        log.error("--remove takes no other argument")
        log.info("Usage: zark setup [--remove]")
        raise SystemExit(2)
    # cfg = Config.load()
    zfs = ZFS(log)

    log.banner("BACKUP SYSTEM SETUP", "Install dependencies and configure sanoid")
    certificates.show_warnings(log)

    # ── 1. Dependencies ──────────────────────────────────────────────────
    log.step(1, 6, "Checking dependencies...")
    missing: list[str] = []
    for cmd, pkg in DEPS.items():
        # Use `which` (real binary at /usr/bin/which), not `command -v`
        # (a shell builtin that subprocess can't invoke without shell=True).
        if sh.run(f"which {cmd}").ok:
            log.ok(f"  {cmd} - installed")
        else:
            missing.append(pkg)
            log.warn(f"  {cmd} - MISSING (package: {pkg})")

    if missing:
        pkgs = " ".join(sorted(set(missing)))
        log.info(f"Installing: {pkgs}")
        r = sh.run(f"apt-get install -y {pkgs}", log=log)
        if r.ok:
            log.ok("All packages installed")
        else:
            log.fatal(
                "Package installation failed",
                solutions=[f"Try: apt-get update && apt-get install -y {pkgs}"],
            )
    else:
        log.ok("All dependencies present")

    # ── 2. Sanoid configuration ──────────────────────────────────────────
    log.step(2, 6, "Configuring sanoid...")

    if not configure_sanoid(zfs, log):
        return

    # ── 3. Enable sanoid timer ───────────────────────────────────────────
    log.step(3, 6, "Enabling sanoid timer...")
    _ = sh.run("systemctl enable sanoid.timer", timeout=10, log=log)
    _ = sh.run("systemctl start sanoid.timer", timeout=10, log=log)
    log.ok("sanoid.timer enabled and started")

    # ── 4. Initial snapshots ─────────────────────────────────────────────
    log.step(4, 6, "Checking snapshots...")
    _initial_snapshots(zfs, log)

    # ── 5. Bookmark anchors ──────────────────────────────────────────────
    log.step(5, 6, "Checking bookmark support on rpool...")
    ensure_bookmark_v2(log)

    # ── 6. Secure Boot binary check ──────────────────────────────────────
    # See _check_secure_boot_alternatives for full rationale on why this
    # exists. TL;DR: subiquity sometimes leaves systems pinned to the
    # older shim variant, which is rejected after SBAT updates.
    log.step(6, 6, "Verifying Secure Boot binaries...")
    _check_secure_boot_alternatives(log)

    _install_guards(log)
    # Space and backup-age alerts: MOTD and an hourly timer (M3 decision 13a).
    alerts.install(log)

    log.banner_ok(
        "SETUP COMPLETE",
        [
            "sanoid installed and running",
            "Snapshots will be taken automatically",
            "",
            f"Next: connect a backup drive and run: {log.W}{zark_command()} backup{log.N}",
        ],
    )
